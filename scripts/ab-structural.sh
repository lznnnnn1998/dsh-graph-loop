#!/usr/bin/env bash
# Structural A/B: same tasks through the stock loop and the graph driver.
#
# By default this uses the deterministic mock LLM and measures STRUCTURE only
# (steps, tool calls, bytes of model-visible text, wall time). It answers "does
# the graph driver add overhead or extra conversation turns", not "is it smarter".
# Set AB_REAL=1 with DEEPSEEK_API_KEY in the environment to run the same tasks
# against the real route; quality still needs human or rubric review.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DSH="${DSH_ROOT:-/Users/zhinan/deepseek-harness}"
LLM_PORT="${LLM_PORT:-8209}"
OUT="${OUT:-$ROOT/docs/AB-STRUCTURAL.md}"
PATCH="$ROOT/packages/loop/dev-headless.patch.yml"
ROWS=$(mktemp /tmp/dsh-ab.XXXXXX)

start_mock() {
  ( cd "$DSH" && exec node --import tsx packages/test-support/llm-mock-server/src/bin.ts \
      --sequence tool_call_success,success --repeat-last --success-text "done" \
      --tool-name read --tool-arguments '{"path":"README.md"}' --port "$LLM_PORT" > "$1" 2>&1 ) &
  MOCK_PID=$!
  for _ in $(seq 1 40); do grep -q '"type":"ready"' "$1" && break; sleep 0.25; done
  grep -q '"type":"ready"' "$1" || { echo "mock failed"; cat "$1"; exit 1; }
}

run_arm() {
  local arm="$1" task="$2" home port log metrics start end
  home=$(mktemp -d "/tmp/dsh-ab-$arm.XXXXXX")
  port=$LLM_PORT
  if [ "${AB_REAL:-0}" != "1" ]; then start_mock "$home/mock.log"; fi
  start=$(node -e 'console.log(Date.now())')
  ( cd "$DSH" && DSH_HOME="$home" DEEPSEEK_BASE_URL="http://127.0.0.1:$port" DEEPSEEK_API_KEY="${DEEPSEEK_API_KEY:-mock}" \
      node --import tsx/esm apps/cli/src/bin.ts --profile headless \
      $([ "$arm" = graph ] && printf '%s' "--patch $PATCH") "$task" > /dev/null 2>&1 ) || true
  end=$(node -e 'console.log(Date.now())')
  if [ "${AB_REAL:-0}" != "1" ]; then kill "$MOCK_PID" 2>/dev/null || true; fi
  log=$(find "$home/sessions" -name "session.v4.jsonl.zstd" | head -1)
  metrics=$(zstd -dc "$log" | node -e '
let d="";process.stdin.on("data",c=>d+=c);process.stdin.on("end",()=>{
 const es=d.trim().split("\n").map(l=>{try{return JSON.parse(l)}catch{return null}}).filter(Boolean)
 const n=t=>es.filter(e=>e.type===t).length
 const userBytes=es.filter(e=>e.type==="user/message").reduce((sum,e)=>sum+JSON.stringify(e.data).length,0)
 const asstBytes=es.filter(e=>e.type==="assistant/message").reduce((sum,e)=>sum+JSON.stringify(e.data).length,0)
 const graphNodes=es.filter(e=>e.type==="user/message"&&JSON.stringify(e.data).includes("[graph node")).length
 const usage=es.filter(e=>e.type==="step/end"&&e.data.usage).reduce((acc,e)=>{acc.input+=e.data.usage.inputTokens||0;acc.output+=e.data.usage.outputTokens||0;return acc},{input:0,output:0})
 console.log(JSON.stringify({turns:n("turn/start"),steps:n("step/start"),tools:n("tool/call"),graphNodes,userBytes,asstBytes,input:usage.input,output:usage.output}))
})')
  printf '%s\t%s\t%s\t%s\n' "$arm" "$task" "$((end-start))" "$metrics" >> "$ROWS"
}

TASKS=(
  "hello"
  "read the README and summarize"
  "find where the config loader is implemented and explain it"
  "fix the failing test in the parser"
)
echo "== stock arm"
for task in "${TASKS[@]}"; do run_arm stock "$task"; done
echo "== graph arm"
for task in "${TASKS[@]}"; do run_arm graph "$task"; done

node - "$ROWS" "$OUT" <<'NODE'
const fs = require('node:fs')
const [rowsFile, outFile] = process.argv.slice(2)
const rows = fs.readFileSync(rowsFile, 'utf8').trim().split('\n').map(line => {
  const [arm, task, wall, json] = line.split('\t')
  return { arm, task, wall: Number(wall), ...JSON.parse(json) }
})
const lines = [
  '# Structural A/B: stock loop vs graph driver',
  '',
  '> Generated by `scripts/ab-structural.sh`. Uses the deterministic mock LLM by default,',
  '> so this measures **structure only** (steps, tool calls, model-visible text, wall time),',
  '> not answer quality. For a real-route run: `AB_REAL=1 DEEPSEEK_API_KEY=... bash scripts/ab-structural.sh`.',
  '',
  '| task | arm | steps | tools | graph nodes | user bytes | assistant bytes | wall ms |',
  '|---|---|---|---|---|---|---|---|',
  ...rows.map(row => `| ${row.task} | ${row.arm} | ${row.steps} | ${row.tools} | ${row.graphNodes} | ${row.userBytes} | ${row.asstBytes} | ${row.wall} |`),
  '',
]
fs.writeFileSync(outFile, lines.join('\n'))
console.log(lines.join('\n'))
NODE
echo "wrote $OUT"
